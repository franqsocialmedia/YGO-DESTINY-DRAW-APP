// Agrupa por nivel y ordena alfabéticamente dentro de cada grupo
    getGroupedByLevel: function () {
        const order = ['Basico', 'Intermedio', 'Competitivo'];
        const groups = { Basico: [], Intermedio: [], Competitivo: [] };
        this.decks.forEach(d => {
            const lvl = order.includes(d.level) ? d.level : 'Basico';
            groups[lvl].push(d.name);
        });
        order.forEach(lvl => groups[lvl].sort((a, b) => a.localeCompare(b, 'es')));
        return groups;
    }
